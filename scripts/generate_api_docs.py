"""Regenerate docs/openapi.json and docs/api-examples.md from a real run.

    python scripts/generate_api_docs.py

Runs the fixture pack through the API on a throwaway SQLite database and
records actual requests and responses, so the examples cannot drift from the
implementation.
"""

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from app.config import Settings  # noqa: E402
from app.db.base import Base  # noqa: E402
from app.db.session import make_engine  # noqa: E402
from app.ingestion.registry import LOAD_ORDER  # noqa: E402
from app.main import create_app  # noqa: E402

DOCS = ROOT / "docs"


def trim(body, max_rows=3):
    if isinstance(body, dict) and isinstance(body.get("rows"), list) and len(body["rows"]) > max_rows:
        body = {**body, "rows": body["rows"][:max_rows] + [f"... {len(body['rows']) - max_rows} more rows"]}
    return body


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        url = f"sqlite:///{tmp}/docs.db"
        Base.metadata.create_all(make_engine(url))
        app = create_app(Settings(database_url=url, log_level="WARNING"))
        (DOCS / "openapi.json").write_text(json.dumps(app.openapi(), indent=2) + "\n")
        client = TestClient(app)
        out = ["# API examples", "",
               "Generated by `scripts/generate_api_docs.py` from a real run of the fixture pack.",
               "Long lists are trimmed. Timestamps are UTC; the frozen evaluation time",
               "2026-10-16T15:00:00+05:30 is 2026-10-16T09:30:00Z.", ""]

        def show(title, method, path, response, request_note=None, body=None, headers=None):
            out.append(f"## {title}\n")
            line = f"{method} {path}"
            out.append("```http")
            out.append(line)
            for k, v in (headers or {}).items():
                out.append(f"{k}: {v}")
            if request_note:
                out.append(request_note)
            if body is not None:
                out.append("")
                out.append(json.dumps(body, indent=2))
            out.append("```\n")
            out.append(f"Response `{response.status_code}`\n")
            out.append("```json")
            out.append(json.dumps(trim(response.json()), indent=2))
            out.append("```\n")

        for dataset in LOAD_ORDER:
            path = ROOT / "fixtures" / f"{dataset}.csv"
            with open(path, "rb") as fh:
                r = client.post(f"/imports/{dataset}", files={"file": (path.name, fh, "text/csv")})
            if dataset == "purchase_order_lines":
                show("Import a dataset", "POST", f"/imports/{dataset}", r,
                     "Content-Type: multipart/form-data  (file=@fixtures/purchase_order_lines.csv)")

        bad = b"source_record_id,receipt_number,receipt_line,po_number,po_line_number,location_code,product_ref," \
              b"accepted_qty,uom,received_at,posting_status\n" \
              b"WMS-X-1,GRN-X,1,PO-501,1,WH-MH-014,WMS-BRC-001,-3,EA,2026-10-15 10:00,POSTED\n"
        r = client.post("/imports/goods_receipt_lines", files={"file": ("bad.csv", bad, "text/csv")})
        show("Import with a rejected row (partial success is explicit)", "POST", "/imports/goods_receipt_lines", r,
             "Content-Type: multipart/form-data  (one row with negative qty and no UTC offset)")

        r = client.post("/detection/runs")
        show("Run detection at the frozen evaluation time", "POST", "/detection/runs", r)

        r = client.get("/exceptions")
        show("List exceptions", "GET", "/exceptions", r)
        exc_id = next(x["id"] for x in r.json() if x["po_number"] == "PO-505")
        show("Inspect one exception with its source records", "GET", f"/exceptions/{exc_id}",
             client.get(f"/exceptions/{exc_id}"))

        r = client.get("/tasks", params={"assignee_id": "HR-102"})
        show("List tasks for an assignee", "GET", "/tasks?assignee_id=HR-102", r)
        task_id = r.json()[0]["id"]

        h = {"X-Actor-Id": "HR-102"}
        r = client.post(f"/tasks/{task_id}/complete", headers=h,
                        json={"resolution_code": "RECEIPT_POSTING_CORRECTED", "evidence_ref": "doc://x"})
        show("Invalid transition", "POST", f"/tasks/{task_id}/complete", r, headers=h,
             body={"resolution_code": "RECEIPT_POSTING_CORRECTED", "evidence_ref": "doc://x"})

        show("Acknowledge", "POST", f"/tasks/{task_id}/acknowledge",
             client.post(f"/tasks/{task_id}/acknowledge", headers=h), headers=h)
        client.post(f"/tasks/{task_id}/start", headers=h)
        body = {"resolution_code": "SHORTAGE_CONFIRMED_CLAIM_RAISED",
                "evidence_ref": "doc://store-014/count-sheet-77", "note": "Physical count matches WMS"}
        hk = {**h, "Idempotency-Key": "complete-7f3a"}
        show("Complete (after start)", "POST", f"/tasks/{task_id}/complete",
             client.post(f"/tasks/{task_id}/complete", headers=hk, json=body), headers=hk, body=body)
        show("Retry the same completion (client timed out)", "POST", f"/tasks/{task_id}/complete",
             client.post(f"/tasks/{task_id}/complete", headers=hk, json=body), headers=hk, body=body)

        hm = {"X-Actor-Id": "HR-201"}
        show("Verify (store manager)", "POST", f"/tasks/{task_id}/verify",
             client.post(f"/tasks/{task_id}/verify", headers=hm, json={"note": "count sheet signed"}),
             headers=hm, body={"note": "count sheet signed"})

        other = client.get("/tasks", params={"assignee_id": "HR-102"}).json()[1]["id"]
        rb = {"assignee_id": "HR-101", "reason": "Asha handled this vendor before"}
        show("Reassign to an ineligible employee is refused", "POST", f"/tasks/{other}/reassign",
             client.post(f"/tasks/{other}/reassign", headers=hm, json=rb), headers=hm, body=rb)
        rb = {"assignee_id": "HR-201", "reason": "Taking over while Dev is on the dock"}
        client.post(f"/tasks/{other}/reassign", headers=hm, json=rb)
        show("Task detail with assignment history and audit events", "GET", f"/tasks/{other}",
             client.get(f"/tasks/{other}"))

        show("Data-quality report", "GET", "/data-quality", client.get("/data-quality"))
        show("Advisory investigation summary (AI disabled -> deterministic)", "GET",
             f"/exceptions/{exc_id}/investigation-summary", client.get(f"/exceptions/{exc_id}/investigation-summary"))

        (DOCS / "api-examples.md").write_text("\n".join(out))
    print(f"wrote {DOCS / 'openapi.json'} and {DOCS / 'api-examples.md'}")


if __name__ == "__main__":
    main()
